    /// The test CA vouches for the harness's own names and no others: a leaf its key
    /// signs for the loopback address *and* another name, served at that address, is
    /// refused by every client that trusts the CA — the harness's own (rustls, as zap
    /// verifies), `openssl verify`, and the target's `curl`. The address it is served
    /// at is one the leaf names and the CA permits, so only the other name can refuse
    /// it. The `curl` leg checks nothing where there is no `curl`.
    #[test]
    fn a_leaf_the_ca_key_signs_for_another_name_is_refused_by_every_client() {
        use crate::differential::pki::tests::{leaf_signed_for, openssl_verify};

        let Some(openssl) = openssl() else { return };
        let scratch = tempfile::tempdir().expect("tempdir");
        let pki =
            Pki::ensure(&scratch.path().join("pki"), &openssl, &server_names()).expect("a pki");
        let ca = pki.dir().join("ca.crt");
        let client = pki.client_config().expect("a client config");
        let serve = |leaf: &Pki| {
            let mut files = BTreeMap::new();
            files.insert("/hello".to_owned(), b"hello bytes".to_vec());
            ContentServer::start_tls(
                LOOPBACK,
                Arc::new(files),
                leaf.server_config().expect("a server config"),
                &Connections::default(),
            )
            .expect("bind loopback")
        };
        let curl = |server: &ContentServer| {
            let mut curl = Command::new("curl");
            for name in [
                "https_proxy",
                "HTTPS_PROXY",
                "ALL_PROXY",
                "CURL_CA_BUNDLE",
                "SSL_CERT_FILE",
                "SSL_CERT_DIR",
            ] {
                curl.env_remove(name);
            }
            curl.args(["-q", "--noproxy", "*"])
                .args(["--proto", "=https", "--proto-redir", "=https", "-fsSL"])
                .arg("--cacert")
                .arg(&ca)
                .arg("--")
                .arg(format!("{}/hello", server.base_url()))
                .output()
        };

        // A leaf for names the CA permits, made the same way, is taken by all three: the
        // refusals below are the constraint's, not the making's.
        let permitted = leaf_signed_for(
            &pki,
            &scratch.path().join("permitted"),
            &openssl,
            "IP:127.0.0.1,DNS:localhost",
        );
        let server = serve(&permitted);
        assert_eq!(server.check_tls(Arc::clone(&client), "/hello"), Ok(()));
        assert!(openssl_verify(&ca, &permitted.dir().join("server.crt")).0);
        let has_curl = if let Ok(fetched) = curl(&server) {
            assert_eq!(fetched.stdout, b"hello bytes", "{fetched:?}");
            true
        } else {
            eprintln!("skipped the curl leg: no `curl` on PATH");
            false
        };

        for names in [
            "IP:127.0.0.1,DNS:example.com",
            "IP:127.0.0.1,IP:10.0.0.1",
            "IP:127.0.0.1,IP:::1",
        ] {
            let rogue = leaf_signed_for(
                &pki,
                &scratch.path().join(names.replace([':', ','], "_")),
                &openssl,
                names,
            );
            let server = serve(&rogue);
            let refused = server
                .get_over_tls(Arc::clone(&client), "/hello")
                .expect_err("a leaf outside the constraints");
            assert!(
                refused.contains("the TLS exchange with 127.0.0.1:")
                    && refused.contains("NameConstraintViolation"),
                "{names}: {refused}"
            );
            let (passed, said) = openssl_verify(&ca, &rogue.dir().join("server.crt"));
            assert!(!passed, "{names}: {said}");
            assert!(
                said.contains("permitted subtree violation"),
                "{names}: {said}"
            );
            if has_curl {
                let fetched = curl(&server).expect("curl");
                assert_eq!(fetched.status.code(), Some(60), "{names}: {fetched:?}");
                assert!(fetched.stdout.is_empty(), "{names}");
            }
        }
    }

    /// The target's own fetch: `curl`, held to https as zap holds it, trusting the CA —
    /// and refusing the server without it. Checks nothing where there is no `curl`.
    #[test]
    fn curl_fetches_over_tls_with_the_ca_and_not_without() {
        let Some(openssl) = openssl() else { return };
        let scratch = tempfile::tempdir().expect("tempdir");
        let (server, pki, _) = tls_server(scratch.path(), &openssl);
        let ca = scratch.path().join("ca-for-curl.crt");
        std::fs::write(&ca, pki.ca_pem()).expect("write");
        let curl = |trust: &[&std::ffi::OsStr], path: &str| {
            let mut curl = Command::new("curl");
            // the developer's own curl settings are no part of this: no `.curlrc`, no
            // proxy, no trust store named from the environment
            for name in [
                "https_proxy",
                "HTTPS_PROXY",
                "ALL_PROXY",
                "CURL_CA_BUNDLE",
                "SSL_CERT_FILE",
                "SSL_CERT_DIR",
            ] {
                curl.env_remove(name);
            }
            curl.args(["-q", "--noproxy", "*"])
                .args(["--proto", "=https", "--proto-redir", "=https", "-fsSL"])
                .args(trust)
                .arg("--")
                .arg(format!("{}{path}", server.base_url()))
                .output()
        };
        let Ok(fetched) = curl(&["--cacert".as_ref(), ca.as_os_str()], "/hello") else {
            eprintln!("skipped: no `curl` on PATH");
            return;
        };
        assert!(
            fetched.status.success(),
            "{}",
            String::from_utf8_lossy(&fetched.stderr)
        );
        assert_eq!(fetched.stdout, b"hello bytes");
        // `--fail` and a real 404: a missing path is a failed fetch with no body
        let missing = curl(&["--cacert".as_ref(), ca.as_os_str()], "/missing").expect("curl");
        assert_eq!(missing.status.code(), Some(22));
        assert!(missing.stdout.is_empty());
        // the system store doesn't hold the test CA
        let untrusted = curl(&[], "/hello").expect("curl");
        assert_eq!(untrusted.status.code(), Some(60));
        assert!(untrusted.stdout.is_empty());
    }
