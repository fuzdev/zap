    #[test]
    fn seeding_lays_out_blake3_dirs_by_url_basename() {
        let mut files = BTreeMap::new();
        files.insert("/a/blob.bin".to_owned(), b"bytes".to_vec());
        files.insert("/copy.bin".to_owned(), b"bytes".to_vec());
        let home = tempfile::tempdir().expect("tempdir");
        seed_content_cache(&files, home.path()).expect("seed");
        let dir = home
            .path()
            .join("cache/files")
            .join(blake3::hash(b"bytes").to_hex().as_str());
        assert_eq!(std::fs::read(dir.join("blob.bin")).expect("blob"), b"bytes");
        assert_eq!(std::fs::read(dir.join("copy.bin")).expect("copy"), b"bytes");
    }

    #[test]
    fn blob_is_deterministic_and_sized() {
        let a = blob_bytes(1000);
        assert_eq!(a.len(), 1000);
        assert_eq!(a, blob_bytes(1000));
        assert_eq!(&blob_bytes(2000)[..1000], &a[..]);
    }

    #[test]
    fn request_path_parses_get_lines() {
        assert_eq!(
            request_path("GET /blob.bin HTTP/1.1\r\nHost: x\r\n\r\n"),
            Some("/blob.bin")
        );
        assert_eq!(request_path("GET /a?b=c HTTP/1.1\r\n"), Some("/a"));
        assert_eq!(request_path("POST /a HTTP/1.1\r\n"), None);
        assert_eq!(request_path(""), None);
    }

    fn fetch(server: &ContentServer, path: &str) -> String {
        let address = server.base_url().trim_start_matches("http://").to_owned();
        let mut stream = TcpStream::connect(address).expect("connect");
        write!(stream, "GET {path} HTTP/1.1\r\nHost: test\r\n\r\n").expect("write");
        let mut response = String::new();
        stream.read_to_string(&mut response).expect("read");
        response
    }

    const LOOPBACK: IpAddr = IpAddr::V4(Ipv4Addr::LOCALHOST);

    #[test]
    fn serves_known_paths_and_404s_the_rest() {
        let mut files = BTreeMap::new();
        files.insert("/hello".to_owned(), b"hello bytes".to_vec());
        let connections = Connections::default();
        let server =
            ContentServer::start(LOOPBACK, Arc::new(files), &connections).expect("bind loopback");
        assert!(server.base_url().starts_with("http://127.0.0.1:"));
        let ok = fetch(&server, "/hello");
        assert!(ok.starts_with("HTTP/1.1 200 OK\r\n"));
        assert!(ok.contains("Content-Length: 11\r\n"));
        assert!(ok.ends_with("\r\n\r\nhello bytes"));
        assert!(fetch(&server, "/missing").starts_with("HTTP/1.1 404"));
        assert_eq!(server.requests(), 2);
        assert_eq!(connections.count(), 2);
    }

    /// A plain and a TLS server started with one count: a connection to either moves
    /// it, so reading the one count misses no listener.
    #[test]
    fn every_server_of_a_run_counts_in_one_place() {
        let Some(openssl) = openssl() else { return };
        let scratch = tempfile::tempdir().expect("tempdir");
        let pki = Pki::ensure(scratch.path(), &openssl, &server_names()).expect("a pki");
        let mut files = BTreeMap::new();
        files.insert("/hello".to_owned(), b"hello bytes".to_vec());
        let files = Arc::new(files);
        let connections = Connections::default();
        let plain = ContentServer::start(LOOPBACK, Arc::clone(&files), &connections)
            .expect("bind loopback");
        let tls = ContentServer::start_tls(
            LOOPBACK,
            files,
            pki.server_config().expect("a server config"),
            &connections,
        )
        .expect("bind loopback");
        assert_eq!(connections.count(), 0);
        fetch(&plain, "/hello");
        assert_eq!(connections.count(), 1);
        tls.get_over_tls(pki.client_config().expect("a client config"), "/hello")
            .expect("a response");
        assert_eq!(connections.count(), 2);
        // a connection that sends nothing is still one
        drop(TcpStream::connect(tls.address).expect("connect"));
        while tls.requests() < 2 {
            std::thread::yield_now();
        }
        assert_eq!(connections.count(), 3);
        assert_eq!((plain.requests(), tls.requests()), (1, 2));
        // another run's count is its own
        assert_eq!(Connections::default().count(), 0);
    }

    /// What a target fetches is what the fixtures name, and no `remote` content: a warm
